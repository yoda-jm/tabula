import { describe, expect, it } from "vitest";
import { A4, PdfDoc, fit, pdfDate, textWidth, winAnsi, wrap } from "./pdf";

/** latin1 reads the bytes of a document as a string, one character per byte. */
const latin1 = (b: Uint8Array) => Array.from(b, (c) => String.fromCharCode(c)).join("");

describe("pdf", () => {
  it("measures Helvetica", () => {
    expect(textWidth("Hang", 10)).toBeCloseTo((722 + 556 + 556 + 556) / 100);
    expect(textWidth("Hang", 10, "bold")).toBeCloseTo((722 + 556 + 611 + 611) / 100);
    expect(textWidth("é", 10)).toBe(textWidth("e", 10));
    expect(textWidth("", 10)).toBe(0);
  });

  it("writes in WinAnsiEncoding", () => {
    expect(winAnsi("A")).toBe(65);
    expect(winAnsi("é")).toBe(0xe9);
    expect(winAnsi("ç")).toBe(0xe7);
    expect(winAnsi("€")).toBe(0x80);
    expect(winAnsi("’")).toBe(0x92);
    expect(winAnsi("œ")).toBe(0x9c);
    expect(winAnsi("日")).toBe(63);
    expect(winAnsi("\n")).toBe(63);
  });

  it("fits a text to a width", () => {
    expect(fit("Short", 100, 10)).toBe("Short");
    const f = fit("A rather long channel name", 50, 10);
    expect(f).toMatch(/…$/);
    expect(textWidth(f, 10)).toBeLessThanOrEqual(50);
    expect(fit("Anything", 1, 10)).toBe("");
  });

  it("wraps a text on lines", () => {
    const text = "SM57 on a short boom stand, pointing at the centre";
    const lines = wrap(text, 80, 10);
    expect(lines.length).toBeGreaterThan(1);
    expect(lines.join(" ")).toBe(text);
    for (const l of lines) expect(textWidth(l, 10)).toBeLessThanOrEqual(80);
    const two = wrap("one two three four five six seven eight nine ten", 50, 10, "regular", 2);
    expect(two).toHaveLength(2);
    expect(two[1]).toMatch(/…$/);
    expect(textWidth(two[1], 10)).toBeLessThanOrEqual(50);
    // a word longer than a line is cut
    const cut = wrap("Supercalifragilistic", 30, 10);
    expect(cut.join("")).toBe("Supercalifragilistic");
    for (const l of cut) expect(textWidth(l, 10)).toBeLessThanOrEqual(30);
    expect(wrap("  ", 50, 10)).toEqual([]);
  });

  it("writes a document a reader can follow", () => {
    const doc = new PdfDoc(A4, { title: "Patch list · Zénith" });
    const p = doc.addPage();
    p.box(10, 10, 100, 20, [0.9, 0.9, 0.9]);
    p.text(20, 25, "Café (live) \\ test", 10, { font: "bold" });
    p.watermark("Generated by Tabula", [0.9, 0.9, 0.9]);
    p.line(10, 40, 200, 40);
    doc.addPage().text(10, 10, "Page 2", 8);
    const out = latin1(doc.bytes(new Date(2026, 9, 30, 21, 45, 0)));
    expect(out.startsWith("%PDF-1.4\n")).toBe(true);
    expect(out.endsWith("%%EOF\n")).toBe(true);
    expect(out).toContain("/Count 2");
    expect(out).toContain("/Title <FEFF");
    expect(out).toContain("(Caf\xe9 \\(live\\) \\\\ test) Tj");

    // the cross-reference table points at each object
    const xref = Number(/startxref\n(\d+)\n%%EOF/.exec(out)![1]);
    expect(out.slice(xref, xref + 5)).toBe("xref\n");
    const entries = out
      .slice(xref)
      .split("\n")
      .filter((l) => / n $/.test(l));
    expect(entries).toHaveLength(9); // catalog, pages, 2 fonts, information, 2 pages and their contents
    entries.forEach((e, i) => {
      expect(e).toHaveLength(19); // 20 bytes with its \n
      expect(out.startsWith(`${i + 1} 0 obj\n`, Number(e.slice(0, 10)))).toBe(true);
    });

    // each stream is as long as it says
    const streams = [...out.matchAll(/<< \/Length (\d+) >>\nstream\n/g)];
    expect(streams).toHaveLength(2);
    for (const m of streams) {
      const start = m.index! + m[0].length;
      expect(out.startsWith("\nendstream", start + Number(m[1]))).toBe(true);
    }

    // the boxes, then the watermark, then the text
    const content = out.slice(streams[0].index!);
    expect(content.indexOf(" re f")).toBeLessThan(content.indexOf("(Generated by Tabula)"));
    expect(content.indexOf("(Generated by Tabula)")).toBeLessThan(content.indexOf("(Caf"));
  });

  it("dates the document", () => {
    expect(pdfDate(new Date(2026, 9, 30, 21, 45, 7))).toMatch(/^D:20261030214507(Z|[+-]\d\d'\d\d')$/);
  });
});
