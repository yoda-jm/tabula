export interface PatchMeta {
  /** the console model, "M32C" */
  model?: string;
  /** tabula's version */
  version?: string;
  /** when it is made, as printed: "30 October 2026, 21:45" */
  date: string;
}

interface Column {
  title: string;
  w: number; // 0: the rest of the width
}

const SIZE = 9.5; // the rows' text
const LINE = 11.5; // a note's second line
const ROW = 17;
const NOTE_LINES = 2;

/** Sheet lays the rows out down the pages, opening a page when one is full. */
class Sheet {
  readonly doc: PdfDoc;
  page: PdfPage;
  y = 0;
  readonly x0 = 42;
  readonly x1: number;
  readonly bottom: number;

  constructor(
    paper: "A4" | "Letter",
    readonly title: string,
    readonly watermark: boolean,
  ) {
    this.doc = new PdfDoc(paper === "Letter" ? LETTER : A4, { title, creator: "Tabula" });
    this.x1 = this.doc.paper.w - 42;
    this.bottom = this.doc.paper.h - 48;
    this.page = this.newPage();
  }

  newPage() {
    const p = this.doc.addPage();
    if (this.watermark) p.watermark(WATERMARK, MARK);
    this.page = p;
    this.y = 44;
    if (this.doc.pages.length > 1) {
      p.text(this.x0, this.y, this.title, 8, { color: INK2 });
      this.y += 18;
    }
    return p;
  }

  /** room makes sure h points fit on this page, opening the next one if not; true when it did. */
  room(h: number): boolean {
    if (this.y + h <= this.bottom) return false;
    this.newPage();
    return true;
  }

  widths(cols: Column[]): number[] {
    const fixed = cols.reduce((a, c) => a + c.w, 0);
    return cols.map((c) => c.w || this.x1 - this.x0 - fixed);
  }

  /** head writes a table's column titles. */
  head(cols: Column[]) {
    const p = this.page;
    const ws = this.widths(cols);
    p.box(this.x0, this.y, this.x1 - this.x0, 15, HEAD);
    let x = this.x0;
    cols.forEach((c, i) => {
      p.text(x + 5, this.y + 10.3, c.title.toUpperCase(), 7, { font: "bold", color: INK2 });
      x += ws[i];
    });
    this.y += 15;
  }

  /** section writes a section's title, keeping it with its column titles and first rows. */
  section(title: string, count: string, cols: Column[]) {
    this.room(26 + 15 + 2 * ROW);
    this.y += 8;
    this.page.text(this.x0, this.y + 12, title, 13, { font: "bold", color: INK });
    this.page.text(this.x0 + textWidth(title, 13, "bold") + 8, this.y + 12, count, 9, { color: INK2 });
    this.y += 18;
    this.head(cols);
  }
}

/** Cell is one cell of a row: its text, and how it is drawn. */
interface Cell {
  text: string;
  bold?: boolean;
  color?: Rgb;
  /** a scribble colour swatch before the text */
  swatch?: number;
  /** wraps on up to NOTE_LINES lines */
  wraps?: boolean;
}

function drawRows(sheet: Sheet, title: string, cols: Column[], rows: Cell[][]) {
  rows.forEach((cells, i) => {
    const ws = sheet.widths(cols);
    const lines = cells.map((c, j) =>
      c.wraps ? wrap(c.text, ws[j] - 10, SIZE, "regular", NOTE_LINES) : [fit(c.text, ws[j] - 10 - (c.swatch ? 11 : 0), SIZE, c.bold ? "bold" : "regular")],
    );
    const h = ROW + LINE * (Math.max(1, ...lines.map((l) => l.length)) - 1);
    if (sheet.room(h)) {
      sheet.page.text(sheet.x0, sheet.y + 10, `${title} (continued)`, 9, { font: "bold", color: INK2 });
      sheet.y += 16;
      sheet.head(cols);
    }
    const p = sheet.page;
    if (i % 2) p.box(sheet.x0, sheet.y, sheet.x1 - sheet.x0, h, ZEBRA);
    let x = sheet.x0;
    cells.forEach((c, j) => {
      let tx = x + 5;
      const sw = c.swatch ? SCRIBBLE[c.swatch % 8] : undefined;
      if (sw) {
        p.box(tx, sheet.y + 5, 7, 7, sw, c.swatch! % 8 === 7 ? INK2 : undefined);
        tx += 11;
      }
      lines[j].forEach((t, k) =>
        p.text(tx, sheet.y + 11.8 + k * LINE, t, SIZE, { font: c.bold ? "bold" : "regular", color: c.color ?? INK }),
      );
      x += ws[j];
    });
    sheet.y += h;
    p.line(sheet.x0, sheet.y, sheet.x1, sheet.y, RULE, 0.4);
  });
}

const INPUT_COLS: Column[] = [
  { title: "Ch", w: 38 },
  { title: "Name", w: 128 },
  { title: "Input", w: 96 },
  { title: "48V", w: 34 },
  { title: "Notes", w: 0 },
];

const OUTPUT_COLS: Column[] = [
  { title: "Output", w: 96 },
  { title: "Carries", w: 170 },
  { title: "Notes", w: 0 },
];

/** patchlistPdf draws the patch list: the listed inputs, then the listed outputs. */
export function patchlistPdf(s: PatchSettings, inputs: InputRow[], outputs: OutputRow[], boxes: Boxes, meta: PatchMeta, now = new Date()): Uint8Array {
  const title = s.title.trim() || "Patch list";
  const sheet = new Sheet(s.paper, s.title.trim() ? `${title} · patch list` : title, s.watermark);
  const p = sheet.page;

  // the heading: the title (under "Patch list" when it is the band's), the
  // details and the contact; the console and its boxes on the right
  let y = sheet.y;
  if (s.title.trim()) {
    p.text(sheet.x0, y + 8, "PATCH LIST", 8, { font: "bold", color: ACCENT });
    y += 12;
  }
  const right = [consoleLabel(meta.model), boxesLabel(boxes), meta.date].filter(Boolean);
  const rightW = Math.max(0, ...right.map((t) => textWidth(t, 8.5)));
  p.text(sheet.x0, y + 19, fit(title, sheet.x1 - sheet.x0 - rightW - 24, 20, "bold"), 20, { font: "bold", color: INK });
  right.forEach((t, i) => p.text(sheet.x1, sheet.y + 9 + i * 11.5, t, 8.5, { align: "right", color: INK2 }));
  y += 26;
  for (const line of [s.details.trim(), s.contact.trim() && `Contact: ${s.contact.trim()}`]) {
    if (!line) continue;
    p.text(sheet.x0, y + 11, fit(line, sheet.x1 - sheet.x0, 10.5), 10.5, { color: INK2 });
    y += 15;
  }
  y = Math.max(y, sheet.y + 9 + right.length * 11.5) + 8;
  p.line(sheet.x0, y, sheet.x1, y, ACCENT, 1.2);
  sheet.y = y + 4;

  const ins = inputs.filter((r) => listed(s, r));
  sheet.section("Inputs", `${ins.length} channel${ins.length === 1 ? "" : "s"}`, INPUT_COLS);
  if (!ins.length) {
    sheet.page.text(sheet.x0 + 5, sheet.y + 13, "No channel is ticked on the Patch list page.", SIZE, { color: INK2 });
    sheet.y += ROW;
  }
  drawRows(
    sheet,
    "Inputs",
    INPUT_COLS,
    ins.map((r) => [
      { text: r.ch, bold: true },
      { text: r.name || "—", bold: !!r.name, swatch: r.color % 8 ? r.color : undefined },
      { text: r.socket },
      { text: r.phantom ? "48V" : "", bold: true, color: PHANTOM },
      { text: noteOf(s, r), wraps: true },
    ]),
  );

  const outs = outputs.filter((r) => listed(s, r));
  if (outs.length) {
    sheet.y += 8;
    sheet.section("Outputs", `${outs.length} output${outs.length === 1 ? "" : "s"}`, OUTPUT_COLS);
    drawRows(
      sheet,
      "Outputs",
      OUTPUT_COLS,
      outs.map((r) => [{ text: r.socket, bold: true }, { text: r.carries }, { text: noteOf(s, r), wraps: true }]),
    );
  }

  // every page's foot: who made it, and the page number
  const pages = sheet.doc.pages;
  pages.forEach((pg, i) => {
    const y = pg.h - 26;
    pg.line(sheet.x0, y - 10, sheet.x1, y - 10, RULE, 0.4);
    const made = [WATERMARK + (meta.version ? ` ${meta.version}` : ""), meta.date].filter(Boolean).join(" · ");
    pg.text(sheet.x0, y, made, 7.5, { color: INK2 });
    pg.text(sheet.x1, y, `Page ${i + 1} of ${pages.length}`, 7.5, { align: "right", color: INK2 });
  });
  return sheet.doc.bytes(now);
}
