// The boxes /-stat/aes50/A and B report, by letter (Maillot's protocol
// document, "/-stat/aes50"): a chain of up to 4, then the preamp types.
const BOXES: Record<string, string> = {
  A: "S16", B: "X32C", C: "X32", D: "DL251", E: "DL251HA", F: "S16B", G: "Z32", H: "T8", I: "X32P", J: "X32RACK",
  K: "X32CORE", L: "M32", M: "M32R", N: "DL16", O: "DL16B", P: "SD16", Q: "SD16B", R: "SD8", S: "SD8B", T: "DL15X",
  U: "DL15XHA", V: "DL231", W: "S32", X: "S32B", Y: "DL32", Z: "DL32B", a: "M32C",
};

/** BOX_OUTS counts the outputs of the boxes that have fewer than 16. */
const BOX_OUTS: Record<string, number> = { S16: 8, S16B: 8, DL16: 8, DL16B: 8, SD16: 8, SD16B: 8, SD8: 8, SD8B: 8 };

/** reportedBoxes names the boxes the console reports on an AES50 port: "DL32", "DL16 + DL16", "" for none. */
export function reportedBoxes(text: string | undefined): string {
  const t = (text ?? "").trim().replace(/^"(.*)"$/, "$1");
  if (Object.values(BOXES).includes(t)) return t;
  const m = /^([A-Za-z]{1,4})[0-4]*$/.exec(t);
  if (!m) return "";
  return [...m[1]]
    .map((c) => BOXES[c])
    .filter(Boolean)
    .join(" + ");
}

/** Boxes names the stage boxes on AES50 A and B: as typed on the page, else as the console reports them. */
export interface Boxes {
  A: string;
  B: string;
}

export function boxesOf(l: Lookup, s: Pick<PatchSettings, "box_a" | "box_b">): Boxes {
  return {
    A: s.box_a.trim() || reportedBoxes(l.text("/-stat/aes50/A")),
    B: s.box_b.trim() || reportedBoxes(l.text("/-stat/aes50/B")),
  };
}

// --- inputs ---

/** nameOf is a strip's name, "" for a placeholder without a letter or a digit ("-"). */
export function nameOf(l: Lookup, strip: string | undefined): string {
  const n = stripName(l, strip);
  return /[\p{L}\p{N}]/u.test(n) ? n : "";
}

/** Socket is where a channel's signal comes from. */
export interface Socket {
  /** "DL32 in 12", "AES50 A 12", "Console in 3"; what feeds it when it is no socket: "Card 5", "USB player L" */
  label: string;
  /** the same for two channels on one socket: "aes50a:12" */
  key: string;
  /** a socket on stage, where something is plugged in: a stage box, the console's own inputs */
  onStage: boolean;
  port: PortSource | null;
}

function socketOf(p: PortSource, boxes: Boxes): Socket {
  const key = `${p.kind}:${p.n}`;
  switch (p.kind) {
    case "aes50a":
    case "aes50b": {
      const box = p.kind === "aes50a" ? boxes.A : boxes.B;
      return { key, port: p, onStage: true, label: box ? `${box} in ${p.n}` : portLabel(p) };
    }
    case "local":
      return { key, port: p, onStage: true, label: `Console in ${p.n}` };
    case "auxin":
      return { key, port: p, onStage: true, label: `Aux in ${p.n}` };
  }
  return { key, port: p, onStage: false, label: portLabel(p) };
}

/** channelSocket follows a channel's source (/ch/NN/config/source) through the input routing to its socket. */
export function channelSocket(l: Lookup, source: number, boxes: Boxes): Socket | null {
  if (!(source > 0)) return null;
  let p: PortSource | null;
  if (source <= 32) p = inputSource(l, source);
  else if (source <= 38) p = auxBlockSource(l.text(`${inputRouting(l)}/AUX`)?.trim() ?? "", source - 32);
  else {
    const label = source === 39 ? "USB player L" : source === 40 ? "USB player R" : sourceLabel(source);
    return { key: `source:${source}`, port: null, onStage: false, label };
  }
  if (p?.kind === "userin") p = userSource(Number(l.value(`/config/userrout/in/${two(p.n)}`) ?? 0));
  return p ? socketOf(p, boxes) : null;
}

export interface InputRow {
  /** the strip: "/ch/12", "/auxin/03" */
  key: string;
  /** "12", "Aux 3" */
  ch: string;
  name: string;
  /** the scribble colour (/config/color) */
  color: number;
  /** the socket, "OFF" without one */
  socket: string;
  /** its key, "" without one */
  from: string;
  onStage: boolean;
  phantom: boolean;
  /** what tabula adds to the note: "stereo L (ch 7-8)", "same input as ch 12" */
  hints: string[];
  /** listed unless unticked: a named channel from a socket on stage, and the first one on it */
  auto: boolean;
}

const INPUT_STRIPS = [
  ...range(1, 32).map((n) => ({ key: `/ch/${two(n)}`, ch: String(n), label: `ch ${n}`, n, link: "/config/chlink" })),
  ...range(1, 8).map((n) => ({ key: `/auxin/${two(n)}`, ch: `Aux ${n}`, label: `aux ${n}`, n, link: "/config/auxlink" })),
];

/** inputRows lists channels 1-32 and aux inputs 1-8. */
export function inputRows(l: Lookup, boxes: Boxes): InputRow[] {
  const first = new Map<string, string>(); // a socket on stage → the first channel on it
  return INPUT_STRIPS.map((s) => {
    const sock = channelSocket(l, Number(l.value(`${s.key}/config/source`) ?? 0), boxes);
    const name = nameOf(l, s.key);
    const hints: string[] = [];
    const odd = s.n % 2 ? s.n : s.n - 1;
    if (Number(l.value(`${s.link}/${odd}-${odd + 1}`)) === 1) {
      const pair = s.key.startsWith("/ch/") ? `ch ${odd}-${odd + 1}` : `aux ${odd}-${odd + 1}`;
      hints.push(`stereo ${s.n === odd ? "L" : "R"} (${pair})`);
    }
    let again = false;
    if (sock?.onStage) {
      const before = first.get(sock.key);
      if (before) {
        hints.push(`same input as ${before}`);
        again = true;
      } else first.set(sock.key, s.label);
    }
    const ha = sock?.port ? headampOfPort(sock.port) : -1;
    return {
      key: s.key,
      ch: s.ch,
      name,
      color: Number(l.value(`${s.key}/config/color`) ?? 0),
      socket: sock?.label ?? "OFF",
      from: sock?.key ?? "",
      onStage: !!sock?.onStage,
      phantom: ha >= 0 && Number(l.value(`${headampPath(ha)}/phantom`)) === 1,
      hints,
      auto: !!sock?.onStage && name !== "" && !again,
    };
  });
}

// --- outputs ---

export interface OutputRow {
  /** "AES50A:1", "OUT:5", "/outputs/aux/02" */
  key: string;
  /** "DL32 on AES50 A", "Console outputs" */
  group: string;
  /** "DL32 out 1", "XLR out 5", "Aux out 2" */
  socket: string;
  /** "MixBus 01 · IEM Remy", "OFF" */
  carries: string;
  /** what tabula adds to the note: "delay 29.2 ms" */
  hints: string[];
  /** listed unless unticked: a box or XLR output that carries something */
  auto: boolean;
}

/** outputCarries tells what an output (/outputs/main/03) carries, and its delay. */
function outputCarries(l: Lookup, node: string): { text: string; hints: string[] } {
  const o = outputSource(Number(l.value(`${node}/src`) ?? 0));
  const name = nameOf(l, o.strip);
  const delay = node.startsWith("/outputs/main/") && Number(l.value(`${node}/delay/on`)) === 1;
  return {
    text: name ? `${o.label} · ${name}` : o.label,
    hints: delay ? [`delay ${(l.text(`${node}/delay/time`) ?? "").trim()} ms`] : [],
  };
}

/** carried tells what an output port's channel carries, following a user patch once. */
function carried(l: Lookup, p: PortSource | null, depth = 0): { text: string; hints: string[] } {
  if (!p) return { text: "OFF", hints: [] };
  if (p.kind === "userout" && depth === 0) {
    return carried(l, userSource(Number(l.value(`/config/userrout/out/${two(p.n)}`) ?? 0)), 1);
  }
  const node = outputNode(p);
  return node ? outputCarries(l, node) : { text: portLabel(p), hints: [] };
}

/**
 * outputRows lists the outputs of the stage boxes (a port is listed when a
 * box is named or reported on it, or a listed channel comes from it), the
 * console's XLR outputs, then its aux, P16 and AES/EBU outputs, left out
 * unless ticked.
 */
export function outputRows(l: Lookup, boxes: Boxes, model: string | undefined, inputs: InputRow[]): OutputRow[] {
  const rows: OutputRow[] = [];
  for (const side of ["A", "B"] as const) {
    const box = boxes[side];
    const used = box !== "" || inputs.some((r) => r.auto && r.from.startsWith(`aes50${side.toLowerCase()}:`));
    const port = portById(side === "A" ? "AES50A" : "AES50B");
    const group = box ? `${box} on AES50 ${side}` : `AES50 ${side}`;
    for (const n of range(1, BOX_OUTS[box] ?? 16)) {
      const c = carried(l, portChannelSource(l, port, n));
      rows.push({
        key: `${port.id}:${n}`,
        group,
        socket: box ? `${box} out ${n}` : `AES50 ${side} out ${n}`,
        carries: c.text,
        hints: c.hints,
        auto: used && c.text !== "OFF",
      });
    }
  }
  const io = localIO(model);
  const local = portById("OUT");
  for (const n of range(1, io.outs)) {
    const c = carried(l, portChannelSource(l, local, n));
    rows.push({ key: `OUT:${n}`, group: "Console outputs", socket: `XLR out ${n}`, carries: c.text, hints: c.hints, auto: c.text !== "OFF" });
  }
  const more = (node: string, count: number, group: string, socket: (n: number) => string) => {
    for (const n of range(1, count)) {
      const c = outputCarries(l, `${node}/${two(n)}`);
      rows.push({ key: `${node}/${two(n)}`, group, socket: socket(n), carries: c.text, hints: c.hints, auto: false });
    }
  };
  if (io.aux > 0) more("/outputs/aux", 6, "Aux outputs", (n) => `Aux out ${n}`);
  if (io.outs > 0) {
    more("/outputs/p16", 16, "P16 (Ultranet)", (n) => `P16 ${n}`);
    more("/outputs/aes", 2, "AES/EBU", (n) => `AES ${n === 1 ? "L" : "R"}`);
  }
  return rows;
}

// --- what is printed ---

/** listed tells whether a row is printed: as ticked by hand, else its default. */
export const listed = (s: PatchSettings, row: { key: string; auto: boolean }) => s.rows[row.key] ?? row.auto;

/** noteOf is a row's note as printed: the one typed, then tabula's hints. */
export function noteOf(s: PatchSettings, row: { key: string; hints: string[] }): string {
  return [s.notes[row.key]?.trim(), ...row.hints].filter(Boolean).join(" · ");
}

/** consoleLabel names the console: "Midas M32C", "Behringer X32". */
export function consoleLabel(model: string | undefined): string {
  const m = (model ?? "").trim();
  if (/^M32/i.test(m)) return `Midas ${m}`;
  if (/^X32/i.test(m)) return `Behringer ${m}`;
  return m;
}

/** boxesLabel says which boxes are on which port: "DL32 on AES50 A". */
export function boxesLabel(b: Boxes): string {
  return [b.A && `${b.A} on AES50 A`, b.B && `${b.B} on AES50 B`].filter(Boolean).join(", ");
}

/** fileName is the PDF's name: "patch-list-gvo-2026-10-30.pdf". */
export function fileName(title: string, date: Date): string {
  const slug = title
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40)
    .replace(/-$/, "");
  const p = (n: number) => String(n).padStart(2, "0");
  const day = `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}`;
  return `patch-list${slug ? "-" + slug : ""}-${day}.pdf`;
}

